// Wires the screenshots in assets/images/guide into src/features/guide/shots.ts, and lists the
// screenshots the guide asks for (`shot: "..."` in src/features/guide/catalog.ts) that are still missing.
//
//   npm run build:guide-shots
//
// Name each screenshot after its step's `shot` key: quran-open-mushaf.png (or .jpg / .webp).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, extname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const shotsDir = join(root, "assets", "images", "guide");
const guideFile = join(root, "src", "features", "guide", "catalog.ts");
const outFile = join(root, "src", "features", "guide", "shots.ts");

const EXTENSIONS = [".png", ".jpg", ".jpeg", ".webp"];

const files = readdirSync(shotsDir)
  .filter((file) => EXTENSIONS.includes(extname(file).toLowerCase()))
  .sort();

const present = new Map();
for (const file of files) {
  const key = file.slice(0, -extname(file).length);
  if (present.has(key)) {
    console.warn(`! two files for "${key}": ${present.get(key)} and ${file} — using the first`);
    continue;
  }
  present.set(key, file);
}

const wanted = [...readFileSync(guideFile, "utf8").matchAll(/shot:\s*"([^"]+)"/g)].map((match) => match[1]);
const missing = [...new Set(wanted)].filter((key) => !present.has(key));
const unused = [...present.keys()].filter((key) => !wanted.includes(key));

// Quoted only when needed, like Prettier, so a rerun leaves a formatted file unchanged.
const prop = (key) => (/^[A-Za-z_$][w$]*$/.test(key) ? key : `"${key}"`);
const lines = [...present].map(([key, file]) => `  ${prop(key)}: require("@/assets/images/guide/${file}"),`);
writeFileSync(
  outFile,
  `// Generated by scripts/build-guide-shots.mjs from assets/images/guide — do not edit by hand.
import type { ImageSourcePropType } from "react-native";

export const GUIDE_SHOTS: Partial<Record<string, ImageSourcePropType>> = {${lines.length ? `\n${lines.join("\n")}\n` : ""}};
`,
);

console.log(`✓ ${present.size} screenshot(s) wired into src/features/guide/shots.ts`);
if (missing.length) console.log(`\n${missing.length} missing:\n${missing.map((key) => `  - ${key}`).join("\n")}`);
if (unused.length) console.log(`\nnot used by any step:\n${unused.map((key) => `  - ${key}`).join("\n")}`);
