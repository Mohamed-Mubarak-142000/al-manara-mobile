const snake = (name) => name.toLowerCase().replace(/[()]/g, "").replace(/\s+/g, "_");

async function fetchArt(folder) {
  // Emoji with skin tones keep their neutral one under Default/.
  const urls = [
    `${BASE}/${encodeURIComponent(folder)}/3D/${snake(folder)}_3d.png`,
    `${BASE}/${encodeURIComponent(folder)}/Default/3D/${snake(folder)}_3d_default.png`,
  ];
  for (const url of urls) {
    const response = await fetch(url);
    if (response.ok) return Buffer.from(await response.arrayBuffer());
  }
  throw new Error(`No 3D art for "${folder}"`);
}

fs.mkdirSync(outDir, { recursive: true });
const lines = [];
for (const [emoji, name, folder] of ART) {
  const file = path.join(outDir, `${name}.png`);
  if (!fs.existsSync(file)) {
    try {
      fs.writeFileSync(file, await fetchArt(folder));
    } catch (error) {
      // KidsArt falls back to the emoji itself.
      console.warn(`skipped ${emoji}: ${error.message}`);
      continue;
    }
  }
  console.log(`${emoji} ${name}.png ← ${folder} (${(fs.statSync(file).size / 1024).toFixed(0)} KB)`);
  lines.push(`  "${emoji}": require("@/assets/images/kids-art/${name}.png"),`);
}

