function archiveReciter(id: number, name: string, item: string, surahList: number[]): Reciter {
  return {
    id,
    name,
    letter: name.charAt(0),
    moshaf: [{ id, name: "حفص عن عاصم - مرتل", rewayaId: HAFS, moshafType: MURATTAL, server: `${ARCHIVE}${item}/`, surahList }],
  };
}

